function photosFor(name: string, hoist: HoistType): StationPhoto[] {
  const src = hoist === "mobile" ? mobileArt : hoist === "none" ? plainArt : ceilingArt;
  const fixture =
    hoist === "mobile"
      ? "a mobile hoist beside a full-size bench"
      : hoist === "none"
        ? "a full-size bench and no hoist"
        : "a ceiling hoist track over a full-size bench";
  return [
    {
      src,
      alt: `Sample illustration, not a photograph: a drawing of a restroom with ${fixture}. This drawing is not ${name}.`,
    },
    {
      src: planArt,
      alt: `Sample floor-plan drawing, not a measured survey of ${name}. It shows a wide room with a bench, toilet, sink, and turning space.`,
    },
  ];
}

